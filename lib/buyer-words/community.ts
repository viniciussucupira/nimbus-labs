export const COMMUNITY_WORDS: Record<LanguageCode, CommunityWords> = { en, es, fr, de, it, nl, pt };

/** A community's words in the store's language. */
export function communityWords(language: unknown): CommunityWords {
  return COMMUNITY_WORDS[parseLanguage(language)];
}

/** "just now", "5 min ago", "3 h ago", then a short date in the store's language. */
export function whenIn(language: unknown, locale: string, seconds: number, nowSeconds = Math.floor(Date.now() / 1000)): string {
  const w = communityWords(language);
  const ago = Math.max(0, nowSeconds - seconds);
  if (ago < 60) return w.justNow;
  if (ago < 3_600) return w.minAgo(Math.floor(ago / 60));
  if (ago < 86_400) return w.hoursAgo(Math.floor(ago / 3_600));
  if (ago < 7 * 86_400) return w.daysAgo(Math.floor(ago / 86_400));
  const date = new Date(seconds * 1000);
  const sameYear = date.getUTCFullYear() === new Date(nowSeconds * 1000).getUTCFullYear();
  return date.toLocaleDateString(locale, { month: "short", day: "numeric", ...(sameYear ? {} : { year: "numeric" }), timeZone: "UTC" });
}

/** When a poll closes, in the store's language: "", "Closed", "Closes in 3 days". */
export function pollWhenIn(language: unknown, ends: number | null | undefined, at = Math.floor(Date.now() / 1000)): string {
  const w = communityWords(language);
  if (!ends) return "";
  if (at >= ends) return w.pollClosed;
  const left = ends - at;
  if (left < 3600) return w.closesInMinutes(Math.max(1, Math.round(left / 60)));
  if (left < 86_400) return w.closesInHours(Math.round(left / 3600));
  return w.closesInDays(Math.round(left / 86_400));
}

